import { describe, it, expect } from "vitest";
import { getGameDetails, resolveFairnessSummary, formatRtp, FAIRNESS_TYPE } from "./casinoGameDetails";

// GAME DETAILS, RTP, RULES AND PROVABLY FAIR INFORMATION — scenario coverage.
// This module is the one place all of this task's real per-game facts live,
// so its own correctness (never fabricating a field, always deriving status
// from the real catalog flag) is what everything downstream depends on.
//
//  1.  Details merge real catalog identity with authored facts     -> below
//  2.  Non-playable onchain games are coming-soon, facts stripped   -> below
//  3.  A game with no authored facts still returns a safe shape     -> below
//  4.  RTP is only present where a real value was authored           -> below
//  5.  Fairness copy never claims provably-fair for an unknown game   -> below
//  6.  On-chain VRF and client-side commit-reveal get distinct, honest copy -> below (the latter always includes its own "demo, not a real server" caveat)
//  7.  RTP formatting matches the task's exact decimal convention      -> below

describe("getGameDetails", () => {
  // GAME_FACTS is empty now — the BetSwirl on-chain games and the
  // placeholder provider games it had authored facts for have been
  // removed, and BGaming's own demo games have no per-game facts recorded
  // yet (see casinoGameDetails.js's own header comment). Every game
  // therefore returns a safe, fact-free shape until a specific
  // `bgaming:<slug>` entry is added.
  it("merges real catalog identity with a safe, fact-free shape for a game with no authored facts", () => {
    const details = getGameDetails({ favId: "bgaming:aloha-king-elvis", title: "Aloha King Elvis", kind: "provider", tags: ["slots"] });
    expect(details.status).toBe("available");
    expect(details.name).toBe("Aloha King Elvis");
    expect(details.description).toBeUndefined();
    expect(details.rtp).toBeUndefined();
    expect(details.fairness).toBeUndefined();
    expect(details.rules).toBeUndefined();
    expect(details.minimumBet).toBeUndefined();
    expect(details.maximumBet).toBeUndefined();
  });

  it("status is always available — there is no chain-gated coming-soon state left", () => {
    const details = getGameDetails({ favId: "bgaming:aloha-king-elvis", title: "Aloha King Elvis", kind: "provider" });
    expect(details.status).toBe("available");
  });

  it("returns null for no game (unavailable/not-found launch states)", () => {
    expect(getGameDetails(null)).toBeNull();
  });
});

describe("resolveFairnessSummary", () => {
  it("never claims provably-fair copy for a game with no fairness data", () => {
    const { heading, summary } = resolveFairnessSummary(undefined);
    expect(heading).toBeNull();
    expect(summary).toBe("Game outcomes are generated by the game's own random-number system.");
  });

  it("labels on-chain VRF games as provably fair with on-chain-specific copy", () => {
    const { heading, summary } = resolveFairnessSummary({ type: FAIRNESS_TYPE.PROVABLY_FAIR, mechanism: "on-chain-vrf" });
    expect(heading).toBe("Provably fair");
    expect(summary).toMatch(/on-chain/);
  });

  it("labels client-side commit-reveal games as provably fair but always includes the demo-mode caveat", () => {
    const result = resolveFairnessSummary({
      type: FAIRNESS_TYPE.PROVABLY_FAIR, mechanism: "client-commit-reveal", note: "This is a demo prototype: the committed seed is generated and held in your browser tab, not on a real server.",
    });
    expect(result.heading).toBe("Provably fair");
    expect(result.note).toMatch(/not on a real server/);
  });
});

describe("formatRtp", () => {
  it("formats to exactly two decimal places with a percent sign", () => {
    expect(formatRtp(98)).toBe("98.00%");
    expect(formatRtp(97.5)).toBe("97.50%");
  });
});
